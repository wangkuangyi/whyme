  const results=[];
  const errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  const check=(name,value)=>{results.push({name,pass:!!value});if(!value)throw new Error(name);};
  const current=()=>page.evaluate(()=>Number(document.body.dataset.angle));
  const settle=()=>page.waitForTimeout(1450);
  await page.setViewportSize({width:1440,height:1000});
  await page.goto('http://127.0.0.1:5173/');
  await page.waitForFunction(()=>window.__WHYME__?.getScene()?.getState().ready);
  await settle();
  check('默认正面机位',await current()===1);
  await page.locator('.directory-item[data-index="1"]').click();await settle();
  check('桌面目录选择',await current()===2);
  await page.locator('.strength.is-active .proof-link').click();
