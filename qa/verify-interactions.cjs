  await page.getByRole('button',{name:'关闭说明'}).click();
  await page.keyboard.press('1');await settle();
  await page.getByRole('button',{name:'角度 2：审美与产品意识',exact:true}).click();await settle();
  check('3D节点点击',await current()===2);
  await page.keyboard.press('1');await settle();
  await page.mouse.move(1100,700);await page.mouse.down();await page.mouse.move(620,700,{steps:14});await page.mouse.up();await settle();
  check('鼠标向左拖动切下一项',await current()===2);
  await page.keyboard.press('1');await settle();await page.mouse.move(1000,400);
  for(let i=0;i<8;i++)await page.mouse.wheel(0,70);
  await settle();check('一次连续滚轮手势只切一格',await current()===2);
  await page.keyboard.press('1');
  for(let i=0;i<10;i++)await page.keyboard.press('ArrowRight');
  await settle();check('快速连续输入不排队',await current()===3);
  check('所有四段文字在DOM内',await page.locator('.strength').count()===4);
  const resume=await page.request.get('http://127.0.0.1:5173/resume.pdf');
  check('简历返回有效PDF',resume.ok()&&resume.headers()['content-type'].includes('pdf'));
  await page.setViewportSize({width:390,height:844});await page.keyboard.press('1');await settle();
  await page.locator('.mobile-tab[data-index="2"]').click();await settle();check('手机目录切换',await current()===3);
  await page.keyboard.press('1');await settle();
  await page.mouse.move(310,350);await page.mouse.down();await page.mouse.move(75,350,{steps:12});await page.mouse.up();await settle();
