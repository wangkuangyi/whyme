async (page) => {
  const checks=[],errors=[],failed=[];
  const check=(name,pass)=>{checks.push({name,pass});if(!pass)throw new Error(name);};
  page.on('pageerror',error=>errors.push(error.message));
  page.on('response',response=>{if(response.status()>=400)failed.push({url:response.url(),status:response.status()});});
  await page.setViewportSize({width:1440,height:1000});
  await page.goto('http://127.0.0.1:4173/');
  await page.waitForFunction(()=>document.body.classList.contains('scene-ready')&&!document.body.classList.contains('static-mode'));
  await page.waitForTimeout(1300);
  check('生产版3D成功加载',true);
  check('生产版没有开发调试接口',await page.evaluate(()=>!window.__WHYME__));
  await page.screenshot({path:'qa/final-desktop.png'});
  await page.keyboard.press('4');await page.waitForTimeout(1500);
  await page.screenshot({path:'qa/final-desktop-04.png'});
  check('生产版可切换至第四机位',await page.locator('#readout').textContent()==='ANGLE 04/04 · MID · 85MM');
  await page.setViewportSize({width:390,height:844});await page.keyboard.press('1');await page.waitForTimeout(1400);
  await page.screenshot({path:'qa/final-mobile.png'});
  const cdp=await page.context().newCDPSession(page);
  await cdp.send('Emulation.setTouchEmulationEnabled',{enabled:true,maxTouchPoints:1});
  await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:310,y:350}]});
  for(let i=0;i<=10;i++)await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:310-i*23,y:350}]});
  await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
  await page.waitForTimeout(1400);
  check('真实触摸事件横滑',await page.evaluate(()=>document.body.dataset.angle==='2'));
  await cdp.detach();
  await page.getByRole('button',{name:'静帧模式',exact:true}).click();await page.waitForTimeout(500);
  await page.keyboard.press('4');await page.waitForTimeout(400);
  await page.screenshot({path:'qa/final-static-mobile.png'});
  check('最终静帧可读取',await page.locator('.poster.is-current').evaluate(img=>img.complete&&img.naturalWidth>0));
  await page.getByRole('button',{name:'启用 3D',exact:true}).click();
  await page.getByRole('button',{name:'静帧模式',exact:true}).click();
  await page.getByRole('button',{name:'启用 3D',exact:true}).click();
  await page.waitForFunction(()=>document.body.classList.contains('scene-ready')&&!document.body.classList.contains('static-mode'));
  await page.waitForTimeout(500);
  check('快速反复切换3D与静帧可恢复',true);
  check('正常生产访问没有失败资源',failed.length===0);
  await page.addInitScript(()=>{const original=window.requestAnimationFrame;window.requestAnimationFrame=callback=>original(()=>setTimeout(()=>callback(performance.now()),60));});
  await page.goto('http://127.0.0.1:4173/');
  await page.waitForFunction(()=>document.body.classList.contains('static-mode'),{timeout:15000});
  check('模拟持续低帧率自动降级',true);
  check('生产无未捕获脚本错误',errors.length===0);
  const downloadPromise=page.waitForEvent('download');
  await page.evaluate(data=>{const a=document.createElement('a');a.href=URL.createObjectURL(new Blob([JSON.stringify(data,null,2)],{type:'application/json'}));a.download='production-results.json';a.click();},{checks,errors,failed});
  await (await downloadPromise).saveAs('qa/production-results.json');
}
